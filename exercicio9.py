#Faça um programa que leia uma lista de 5 números inteiros digitados pelo usuário e calcule a soma desses números.
numeroum = int(input("Digite o primeiro número "))
numerodois = int(input("Digite o segundo número "))
numerotres = int(input("Digite o terceiro número "))
numeroquatro = int(input("Digite o quarto número "))
numerocinco = int(input("Digite o quinto número "))
soma = numeroum + numerodois + numerotres + numeroquatro + numerocinco
print(soma)
